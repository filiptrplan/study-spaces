// The app switches to light by setting data-mantine-color-scheme on <html>. The film needs a light phone next to dark
// UI, so this copies the app's light tokens into a .promo-light class (and re-points Mantine's mapped variables).
import { readFileSync, writeFileSync } from 'node:fs';
const css = readFileSync('../frontend/src/styles.css', 'utf8');
const m = css.match(/:root\[data-mantine-color-scheme='light'\]\s*\{([\s\S]*?)\n\}/);
if (!m) throw new Error('light block not found');
const theme = readFileSync('../frontend/src/theme/theme.tsx', 'utf8');
const vars = [...theme.matchAll(/'(--mantine-[a-z-]+)': 'var\((--color-[a-z-]+)\)'/g)].map((x) => `  ${x[1]}: var(${x[2]});`).join('\n');
writeFileSync('src/light.css', `/* generated by scripts/light-tokens.mjs from frontend/src/styles.css */\n.promo-light {\n${m[1]}\n${vars}\n  color-scheme: light;\n}\n`);
console.log('ok');
